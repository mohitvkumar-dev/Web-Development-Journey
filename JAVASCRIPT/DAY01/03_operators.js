//Arithmetic Operators

let a=10;
 let b=20;
 console.log(a+b);
 console.log(a-b);
 console.log(a*b);
 console.log(a/b);


 // Unary Operators
 console.log(a++); 
 console.log(++a); 
 console.log(--a);
 console.log(a--);

 // Assignment Operators

 let data = b;
 console.log(data);


